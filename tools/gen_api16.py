"""Glue for the game's 16-bit API imports -> src/rt/api_glue.c

Each import api_<MOD>_<ord> pops its pascal arguments from the guest stack
(above the far return address) and calls the native
`u32 w16_<Name>(args)` (arguments left to right; word -> u16 / s16,
long / pointers -> u32 far value).  The result goes to DX:AX.  Natives not
written yet are weak stubs that log the call and return 0.  Register-
convention APIs (DOS3Call, InitTask, __fpMath) get `void w16_<Name>(void)`
working on cpu directly.

usage: python tools/gen_api16.py src/gen/rc/apis.txt src/rt/api_glue.c
"""
import sys

REGISTER = {'DOS3Call', 'InitTask', '__fpMath'}


def main():
    src, out = sys.argv[1:3]
    lines = ['/* generated by tools/gen_api16.py - do not edit */', '#include "rt.h"', '',
             'extern int api_log_on;', 'u32 rt_api_ret;', 'static int stub_n;', '']
    for l in open(src):
        w = l.split()
        mod, o, name, args = w[0], int(w[1]), w[2], w[3:]
        fn = 'api_%s_%d' % (mod, o)
        if name in REGISTER:
            lines.append('void __attribute__((weak)) w16_%s(void) { if (stub_n++ < 200) rt_log("STUB %s.%s\\n"); }' % (name, mod, name))
            lines.append('void %s(void) { if (api_log_on) rt_log("api %s\\n"); w16_%s(); cpu.r[R_ESP] = (u16)(cpu.r[R_ESP] + 4); }' % (fn, name, name))
            continue
        sizes = [2 if a in ('word', 's_word') else 4 for a in args]
        total = sum(sizes)
        ctypes = ['s16' if a == 's_word' else 'u16' if a == 'word' else 'u32' for a in args]
        params = ', '.join('%s a%d' % (t, i) for i, t in enumerate(ctypes)) or 'void'
        names = ', '.join('a%d' % i for i in range(len(args)))
        fmt = ' '.join('%x' for _ in args)
        lines.append('u32 __attribute__((weak)) w16_%s(%s) { %s if (stub_n++ < 200) rt_log("STUB %s.%s(%s)\\n"%s); return 0; }'
                     % (name, params, ' '.join('(void)a%d;' % i for i in range(len(args))), mod, name, fmt,
                        (', ' + ', '.join('(u32)a%d' % i for i in range(len(args)))) if args else ''))
        body = ['void %s(void)' % fn, '{']
        # last argument is nearest the return address
        off = 4
        rd = {}
        for i in reversed(range(len(args))):
            rd[i] = ('(%s)RD16(STK(%d))' % (ctypes[i], off)) if sizes[i] == 2 else ('(RD16(STK(%d)) | ((u32)RD16(STK(%d)) << 16))' % (off, off + 2))
            off += sizes[i]
        for i in range(len(args)):
            body.append('    %s a%d = %s;' % (ctypes[i], i, rd[i]))
        body.append('    rt_api_ret = RD16(STK(0)) | ((u32)RD16(STK(2)) << 16);   /* caller (debugging) */')
        body.append('    if (api_log_on) rt_log("api %s(%s)\\n"%s);' % (name, fmt, (', ' + ', '.join('(u32)a%d' % i for i in range(len(args)))) if args else ''))
        body.append('    cpu.r[R_ESP] = (u16)(cpu.r[R_ESP] + %d);' % (4 + total))
        body.append('    u32 r = w16_%s(%s);' % (name, names))
        body.append('    set_ret(r);')
        body.append('}')
        lines += body
    lines.append('')
    open(out, 'w').write('\n'.join(lines))


if __name__ == '__main__':
    main()
